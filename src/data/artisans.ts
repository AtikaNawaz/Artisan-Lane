export function getArtisanById(id: string) {
  return artisans.find((a) => a.id === id);
}

export function getArtisanBySlug(slug: string) {
  return artisans.find((a) => a.slug === slug);
}

export function getNewSellerSpotlight() {
  const newcomers = artisans.filter((a) => a.isNew && a.isApproved);
  if (!newcomers.length) return artisans[0];
  // Rotate weekly based on ISO week number
  const week = Math.floor(Date.now() / (7 * 24 * 60 * 60 * 1000));
  return newcomers[week % newcomers.length];
}
