export function getProductById(id: string) {
  return products.find((p) => p.id === id);
}

export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getProductsByArtisan(artisanId: string) {
  return products.filter((p) => p.artisanId === artisanId);
}

export function getProductsByCategory(categoryId: string) {
  return products.filter((p) => p.categoryId === categoryId);
}

export function getFeaturedProducts() {
  return products.filter((p) => p.featured);
}

export function getLaunchCollection() {
  return products.filter((p) => p.launchCollection);
}

export function getTrendingProducts(limit = 8) {
  return [...products].sort((a, b) => b.salesCount - a.salesCount).slice(0, limit);
}

export function getCategoriesWithCounts() {
  return categories.map((c) => ({
    ...c,
    productCount: products.filter((p) => p.categoryId === c.id).length,
  }));
}
